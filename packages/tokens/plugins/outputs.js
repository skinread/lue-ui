// lueJs — tokens.js and tokens.d.ts (RFC-0001 §1): every public token's name as a `var(--lue-…)` string, and its
// literal value in each theme context (fluid sizes at their 1280 px maximum, rem as px), for scripts, tests and React.
//
// lueFigma — figma/<context>.tokens.json: one DTCG file per theme context, aliases resolved, for importing as Figma
// variable modes. Only the types Figma variables hold (colour, dimension, number, font family and weight, duration);
// gradients, shadows and text styles stay in CSS.
import { contexts, inputFor, literal, pxOf } from './lue.js';

const isPublic = (exclude) => (id) => !exclude.some((glob) => id.startsWith(glob.replace(/\*+$/, '')));

export function lueJs({ variableName, exclude = [] }) {
  return {
    name: 'lue-js',
    build({ resolver, tokens, outputFile }) {
      const ids = Object.keys(tokens).filter(isPublic(exclude)).sort();
      const ctxs = contexts(resolver);
      const names = Object.fromEntries(ids.map((id) => [id, `var(${variableName(tokens[id])})`]));
      const values = Object.fromEntries(ctxs.map((ctx) => {
        const set = resolver.apply(inputFor(ctx));
        return [ctx, Object.fromEntries(ids.map((id) => [id, literal(set[id])]))];
      }));
      outputFile('tokens.js', `// Lue UI tokens, generated by Terrazzo from packages/tokens/src. Don't edit.
/** Every public token as a CSS variable reference, which follows the theme of the element it's used on. */
export const tokens = Object.freeze(${JSON.stringify(names, null, 2)});
/** Theme contexts, primary first. */
export const themes = Object.freeze(${JSON.stringify(ctxs)});
/** Literal values per theme context (fluid sizes at 1280 px, rem as px). */
export const values = Object.freeze(${JSON.stringify(values, null, 2)});
`);
      outputFile('tokens.d.ts', `// Lue UI tokens, generated by Terrazzo from packages/tokens/src. Don't edit.
export type TokenName =
${ids.map((id) => `  | '${id}'`).join('\n')};
export type Theme = ${ctxs.map((c) => `'${c}'`).join(' | ')};
/** Every public token as a CSS variable reference, which follows the theme of the element it's used on. */
export declare const tokens: Readonly<Record<TokenName, \`var(--lue-\${string})\`>>;
/** Theme contexts, primary first. */
export declare const themes: readonly Theme[];
/** Literal values per theme context (fluid sizes at 1280 px, rem as px). */
export declare const values: Readonly<Record<Theme, Readonly<Record<TokenName, string>>>>;
`);
    },
  };
}

const FIGMA_TYPES = new Set(['color', 'dimension', 'number', 'fontFamily', 'fontWeight', 'duration']);

export function lueFigma({ exclude = [] }) {
  return {
    name: 'lue-figma',
    build({ resolver, outputFile }) {
      for (const ctx of contexts(resolver)) {
        const set = resolver.apply(inputFor(ctx));
        const doc = { $description: `Lue UI, theme ${ctx}. Generated from packages/tokens/src; import as one Figma variable mode.` };
        for (const id of Object.keys(set).filter(isPublic(exclude)).sort()) {
          const t = set[id];
          if (!FIGMA_TYPES.has(t.$type)) continue;
          let $value = t.$value;
          if (t.$type === 'color') $value = { colorSpace: 'srgb', components: hexToRgb(t.$value.hex), alpha: t.$value.alpha ?? 1, hex: t.$value.hex };
          if (t.$type === 'dimension') $value = { value: pxOf(t.$value), unit: 'px' };
          if (t.$type === 'number' && t.$extensions?.lue?.unit) continue; // em and ch numbers have no Figma unit
          let node = doc;
          const path = id.split('.');
          for (const key of path.slice(0, -1)) node = node[key] ??= {};
          node[path.at(-1)] = { $type: t.$type, $value, $description: t.$description };
        }
        outputFile(`figma/${ctx}.tokens.json`, JSON.stringify(doc, null, 2) + '\n');
      }
    },
  };
}

const hexToRgb = (hex) => [1, 3, 5].map((i) => +(parseInt(hex.slice(i, i + 2), 16) / 255).toFixed(4));
